test("Explain this result shows a grounded AI Maintenance Explanation with citations", async ({
  page,
}) => {
  await page.goto("/upload");
  await page.getByRole("button", { name: /try sample data/i }).click();
  await expect(page.getByText(/hours/)).toBeVisible({ timeout: 20_000 });
  await page.getByRole("button", { name: /explain this result/i }).click();
  await expect(page.getByText(/AI Maintenance Explanation/i)).toBeVisible();
  await expect(page.getByText(/Generated by:/i)).toBeVisible({ timeout: 20_000 });
  await expect(page.getByText(/model result/i)).toBeVisible();

  // Section 12 regression: no raw Markdown artifacts rendered to the user.
  const bodyText = await page.locator("main").innerText();
  expect(bodyText).not.toMatch(/\*\*/);
  expect(bodyText).not.toMatch(/^##/m);
});

