test("Generic non-FEMTO CSV is treated as out-of-distribution, not a FEMTO prediction", async ({
  page,
}) => {
  // Real college LogFile_*.csv files are ~137MB each (full-run vibration capture) -
  // impractical for an E2E upload. A small, structurally-valid but non-FEMTO-shaped
  // CSV (same column names college/generic data use, no FEMTO header) exercises the
  // same RETRAIN_REQUIRED/suppression path the frontend's handleGenericFile takes.
  await page.goto("/upload");
  await page.setInputFiles('[data-testid="file-input"]', {
    name: "generic-vibration.csv",
    mimeType: "text/csv",
    buffer: Buffer.from(
      "vibration_x,vibration_y\n" + Array.from({ length: 50 }, () => "0.1,0.2").join("\n") + "\n",
    ),
  });
  await page.getByRole("button", { name: /analyze bearing/i }).click();
  await expect(
    page.getByText(
      /RUL suppressed|outside the training distribution|RETRAIN_REQUIRED|won't succeed on retry/i,
    ),
  ).toBeVisible({ timeout: 20_000 });
});
