"use client";

import { useEffect, useState } from "react";
import {
  ApiError,
  EvaluationResponse,
  HealthIndicatorComparisonResponse,
  HiddenSetEvaluationResponse,
  TrajectoryResponse,
  getHealthIndicatorComparison,
  getHiddenSetEvaluation,
  getModelEvaluation,
  getTrajectory,
  getTrajectoryBearings,
} from "@/lib/api";
import { BarChart } from "@/components/BarChart";
import { MultiSeriesChart } from "@/components/MultiSeriesChart";

type State =
  | { status: "loading" }
  | { status: "error"; error: string }
  | {
      status: "ready";
      evaluation: EvaluationResponse;
      hiddenSet: HiddenSetEvaluationResponse | null;
      hiComparison: HealthIndicatorComparisonResponse | null;
      scatter: TrajectoryResponse[] | null;
    };

export default function EvaluationPage() {
  const [state, setState] = useState<State>({ status: "loading" });

  useEffect(() => {
    (async () => {
      try {
        const evaluation = await getModelEvaluation();
        // Hidden-set / HI-comparison / full trajectory set are each optional
        // deployment artifacts - a missing one degrades that section, not
        // the whole page (ApiError on any one of these is swallowed to null).
        const [hiddenSet, hiComparison, scatter] = await Promise.all([
          getHiddenSetEvaluation().catch(() => null),
          getHealthIndicatorComparison().catch(() => null),
          loadAllTrajectories().catch(() => null),
        ]);
        setState({ status: "ready", evaluation, hiddenSet, hiComparison, scatter });
      } catch (err) {
        setState({ status: "error", error: (err as ApiError).detail ?? String(err) });
      }
    })();
  }, []);

  return (
    <main className="mx-auto flex max-w-4xl flex-col gap-8 px-6 py-16">
      <header>
        <h1 className="text-2xl font-semibold tracking-tight">Model evaluation</h1>
        <p className="mt-1 text-sm text-foreground-muted">
          Real evaluation numbers read verbatim from committed artifacts
          (<code>reports/metrics/rul_evaluation.json</code>,{" "}
          <code>deploy_data/hidden_set_evaluation.json</code>,{" "}
          <code>reports/metrics/health_indicator_comparison.json</code>), generated by
          <code> scripts/evaluate_models.py</code> / <code>scripts/score_hidden_set.py</code> /
          <code> scripts/build_health.py</code>. Nothing on this page is recomputed in the browser.
          FEMTO uses leave-one-bearing-out; college uses a strict chronological walk-forward.
        </p>
      </header>

      {state.status === "loading" && <p className="text-sm">Loading…</p>}
      {state.status === "error" && (
        <p className="rounded-lg border border-red-300 bg-red-50 p-4 text-sm text-red-700 dark:border-red-900 dark:bg-red-950 dark:text-red-300">
          {state.error}
        </p>
      )}

      {state.status === "ready" && (
        <>
          <FemtoHeadline evaluation={state.evaluation} />
          <PerBearingMae evaluation={state.evaluation} />
          <SignedError evaluation={state.evaluation} />
          {state.scatter && <ActualVsPredictedScatter trajectories={state.scatter} />}
          {state.hiddenSet && <HiddenSetSection hiddenSet={state.hiddenSet} />}
          {state.hiComparison && <HiComparisonSection hiComparison={state.hiComparison} />}
          <CollegeCaseStudy evaluation={state.evaluation} />
        </>
      )}
    </main>
  );
}

async function loadAllTrajectories(): Promise<TrajectoryResponse[]> {
  const { bearings } = await getTrajectoryBearings();
  return Promise.all(bearings.map((b) => getTrajectory(b)));
}

function FemtoHeadline({ evaluation }: { evaluation: EvaluationResponse }) {
  const et = evaluation.femto_lobo_overall_by_model.extra_trees;
  const naive = evaluation.femto_lobo_overall_by_model.naive;
  const improvementPct = et && naive ? ((naive.mae_seconds - et.mae_seconds) / naive.mae_seconds) * 100 : null;
  return (
    <section>
      <h2 className="text-lg font-semibold">FEMTO headline (leave-one-bearing-out)</h2>
      <div className="mt-2 grid grid-cols-2 gap-3 sm:grid-cols-4">
        <Stat label="ExtraTrees MAE" value={et ? `${(et.mae_seconds / 3600).toFixed(2)} h` : "—"} />
        <Stat label="Naive MAE" value={naive ? `${(naive.mae_seconds / 3600).toFixed(2)} h` : "—"} />
        <Stat label="Improvement vs naive" value={improvementPct !== null ? `${improvementPct.toFixed(1)}%` : "—"} />
        <Stat
          label="Over-estimate rate (ET)"
          value={et?.overestimate_rate !== undefined ? `${(et.overestimate_rate * 100).toFixed(1)}%` : "—"}
        />
      </div>
      <p className="mt-2 text-xs text-foreground-muted">
        n = {et?.n ?? "?"} predictions across 6 held-out bearings. A model that does not beat naive
        on a given bearing is reported below, not hidden.
      </p>
    </section>
  );
}

function Stat({ label, value }: { label: string; value: string }) {
  return (
    <div className="rounded-lg border border-surface-border p-3">
      <dt className="text-xs text-foreground-muted">{label}</dt>
      <dd className="mt-0.5 text-lg font-semibold">{value}</dd>
    </div>
  );
}

function PerBearingMae({ evaluation }: { evaluation: EvaluationResponse }) {
  const bearings = [...new Set(evaluation.femto_lobo.map((r) => r.held_out_bearing))].sort();
  const et = bearings.map(
    (b) => evaluation.femto_lobo.find((r) => r.held_out_bearing === b && r.model === "extra_trees")!.mae_seconds / 3600
  );
  const naive = bearings.map(
    (b) => evaluation.femto_lobo.find((r) => r.held_out_bearing === b && r.model === "naive")!.mae_seconds / 3600
  );
  return (
    <section>
      <h2 className="text-lg font-semibold">Per-bearing MAE</h2>
      <BarChart
        categories={bearings.map((b) => b.replace("femto:", ""))}
        series={[
          { label: "ExtraTrees", color: "#60a5fa", values: et },
          { label: "naive", color: "#94a3b8", values: naive },
        ]}
        yLabel="MAE (hours)"
      />
    </section>
  );
}

function SignedError({ evaluation }: { evaluation: EvaluationResponse }) {
  const bearings = [...new Set(evaluation.femto_lobo.map((r) => r.held_out_bearing))].sort();
  const et = bearings.map(
    (b) =>
      (evaluation.femto_lobo.find((r) => r.held_out_bearing === b && r.model === "extra_trees")
        ?.mean_signed_error_seconds ?? 0) / 3600
  );
  return (
    <section>
      <h2 className="text-lg font-semibold">Per-bearing signed error (ExtraTrees)</h2>
      <BarChart
        categories={bearings.map((b) => b.replace("femto:", ""))}
        series={[{ label: "mean signed error", color: "#f59e0b", values: et }]}
        yLabel="signed error (hours)"
      />
      <p className="mt-1 text-xs text-foreground-muted">
        Positive = unsafe RUL over-prediction (more life claimed than remained). Negative =
        conservative under-prediction.
      </p>
    </section>
  );
}

function ActualVsPredictedScatter({ trajectories }: { trajectories: TrajectoryResponse[] }) {
  const series = trajectories.map((t, i) => {
    const predictedBySeq = new Map(
      t.held_out_predicted_rul_seconds.sequence_index.map((seq, j) => [
        seq,
        t.held_out_predicted_rul_seconds.predicted_rul_seconds[j],
      ])
    );
    const points = t.sequence_index
      .map((seq, j) => {
        const actual = t.actual_rul_seconds[j];
        const predicted = predictedBySeq.get(seq);
        if (actual === null || predicted === undefined) return null;
        return { x: actual / 3600, y: predicted / 3600 };
      })
      .filter((p): p is { x: number; y: number } => p !== null);
    const palette = ["#60a5fa", "#34d399", "#f472b6", "#c084fc", "#f59e0b", "#94a3b8"];
    return { label: t.bearing_run_id.replace("femto:", ""), color: palette[i % palette.length], points };
  });
  return (
    <section>
      <h2 className="text-lg font-semibold">Actual vs predicted RUL (held-out, all learning bearings)</h2>
      <MultiSeriesChart series={series} mode="points" referenceLine xLabel="actual RUL (hours)" yLabel="predicted RUL (hours)" />
      <p className="mt-1 text-xs text-foreground-muted">
        Dashed line is the perfect-prediction reference (actual = predicted). Each point is one
        leave-one-bearing-out held-out acquisition — the model never saw that bearing during
        training.
      </p>
    </section>
  );
}

function HiddenSetSection({ hiddenSet }: { hiddenSet: HiddenSetEvaluationResponse }) {
  const official = hiddenSet.results.official.per_bearing;
  function summarize(model: string) {
    const rows = official.filter((r) => r.model === model);
    const mae = rows.reduce((a, r) => a + Math.abs(r.error_seconds), 0) / rows.length;
    const score = rows.reduce((a, r) => a + r.phm2012_score, 0) / rows.length;
    const over = rows.filter((r) => r.error_seconds < 0).length;
    return { mae, score, over, n: rows.length };
  }
  const et = summarize("extra_trees");
  const naive = summarize("naive");
  return (
    <section>
      <h2 className="text-lg font-semibold">Hidden FEMTO challenge (Full_Test_Set, scored once post-freeze)</h2>
      <p className="mt-1 text-xs text-foreground-muted">{hiddenSet.convention}</p>
      <div className="mt-2 grid grid-cols-2 gap-3 sm:grid-cols-4">
        <Stat label="ExtraTrees MAE" value={`${(et.mae / 3600).toFixed(2)} h`} />
        <Stat label="ExtraTrees PHM2012 score" value={et.score.toFixed(4)} />
        <Stat label="Over-estimated bearings" value={`${et.over} / ${et.n}`} />
        <Stat label="Naive MAE (reference)" value={`${(naive.mae / 3600).toFixed(2)} h`} />
      </div>
      <p className="mt-2 text-xs text-foreground-muted">
        Ground truth: official challenge table (<code>docs/decisions.md</code> D16/D17). Bearing1_4&apos;s
        actual RUL differs between the official table (339s) and an archive-derived re-count
        (2890s) — this view uses the official, citable value; the archive-derived variant is also
        available in the underlying artifact for cross-checking.
      </p>
    </section>
  );
}

function HiComparisonSection({ hiComparison }: { hiComparison: HealthIndicatorComparisonResponse }) {
  const variants: Array<[string, typeof hiComparison.reference_hi]> = [
    ["reference_hi (selected)", hiComparison.reference_hi],
    ["transparent_hi (legacy)", hiComparison.transparent_hi],
    ["pca_hi (legacy)", hiComparison.pca_hi],
  ];
  return (
    <section>
      <h2 className="text-lg font-semibold">Health indicator comparison</h2>
      <p className="mt-1 text-xs text-foreground-muted">{hiComparison.selection_reason}</p>
      <table className="mt-2 w-full text-left text-xs">
        <thead className="text-foreground-muted">
          <tr>
            <th className="py-1 pr-3">Variant</th>
            <th className="py-1 pr-3">Status</th>
            <th className="py-1 pr-3">Mean |Spearman|</th>
            <th className="py-1 pr-3">Mean % pinned at 1.0</th>
          </tr>
        </thead>
        <tbody>
          {variants.map(([label, v]) => {
            // reference_hi nests its numbers under `pooled` (and `leave_one_bearing_out`)
            // instead of the top level the legacy transparent_hi/pca_hi variants use -
            // read whichever is present rather than assuming the flat shape.
            const spearman = v.mean_spearman ?? v.pooled?.mean_spearman;
            const pinning = v.pinning ?? v.pooled?.pinning;
            return (
              <tr key={label} className="border-t border-surface-border">
                <td className="py-1 pr-3 font-mono">{label}</td>
                <td className="py-1 pr-3">{v.status}</td>
                <td className="py-1 pr-3">{spearman !== undefined ? Math.abs(spearman).toFixed(3) : "n/a"}</td>
                <td className="py-1 pr-3">
                  {pinning ? `${pinning.mean_pct_at_one.toFixed(1)}%` : "n/a (fixed, D18)"}
                </td>
              </tr>
            );
          })}
        </tbody>
      </table>
      <p className="mt-2 text-xs text-foreground-muted">
        Transparent/PCA HI are retained as documented failure modes (docs/decisions.md D18), not
        deleted — the pinning and low-trend numbers above are why reference_hi was selected.
      </p>
    </section>
  );
}

function CollegeCaseStudy({ evaluation }: { evaluation: EvaluationResponse }) {
  if (!evaluation.college_mean_mae_by_model) return null;
  return (
    <section className="rounded-lg border border-caution/30 bg-caution/10 p-4">
      <h2 className="text-sm font-medium text-caution">College case study — walk-forward</h2>
      <p className="mt-1 text-xs text-foreground-muted">
        129 <code>LogFile_*.csv</code> files, one physical bearing, ~128-hour continuous run at
        25.6 kHz: vibration X/Y, bearing temperature, ambient temperature. Evaluated with a strict
        chronological expanding-window walk-forward (train on the past, test on the future) — the
        same discipline as FEMTO&apos;s leave-one-bearing-out, adapted to a single run.
      </p>
      <p className="mt-2 text-xs font-medium text-caution">{evaluation.college_naive_caveat}</p>
      <table className="mt-2 w-full text-left text-sm text-caution">
        <tbody>
          {Object.entries(evaluation.college_mean_mae_by_model).map(([model, mae]) => (
            <tr key={model}>
              <td className="py-1 pr-3 font-mono">{model}</td>
              <td className="py-1">{mae.toFixed(0)}s</td>
            </tr>
          ))}
        </tbody>
      </table>
      {evaluation.college_overall_by_model?.extra_trees && (
        <p className="mt-2 text-xs text-caution">
          ExtraTrees over-estimated RUL on{" "}
          {evaluation.college_overall_by_model.extra_trees.overestimate_rate !== undefined
            ? `${(evaluation.college_overall_by_model.extra_trees.overestimate_rate * 100).toFixed(0)}%`
            : "an"}{" "}
          of walk-forward predictions on this run.
        </p>
      )}
      <p className="mt-2 text-xs text-caution">
        Domain-shift limitation: the FEMTO-fit RUL/HI models are never applied to college data as
        if validated (docs/decisions.md D11) — college is evaluated with its own model fit on its
        own chronological folds. A single run cannot demonstrate cross-machine generalisation.
      </p>
    </section>
  );
}
