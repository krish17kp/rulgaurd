"use client";

import { useEffect, useState } from "react";
import { ApiError, EvaluationResponse, getModelEvaluation } from "@/lib/api";

type State =
  | { status: "loading" }
  | { status: "error"; error: string }
  | { status: "ready"; data: EvaluationResponse };

export default function EvaluationPage() {
  const [state, setState] = useState<State>({ status: "loading" });

  useEffect(() => {
    getModelEvaluation()
      .then((data) => setState({ status: "ready", data }))
      .catch((err: ApiError) => setState({ status: "error", error: err.detail }));
  }, []);

  return (
    <main className="mx-auto flex max-w-3xl flex-col gap-6 px-6 py-16">
      <header>
        <h1 className="text-2xl font-semibold tracking-tight">Model reliability</h1>
        <p className="mt-1 text-sm text-zinc-500">
          Real evaluation numbers read from <code>reports/metrics/rul_evaluation.json</code>,
          generated by <code>scripts/evaluate_models.py</code>. FEMTO uses
          leave-one-bearing-out (no bearing appears in both its own train and test fold);
          college uses a strict chronological walk-forward.
        </p>
      </header>

      {state.status === "loading" && <p className="text-sm">Loading…</p>}
      {state.status === "error" && (
        <p className="rounded-lg border border-red-300 bg-red-50 p-4 text-sm text-red-700 dark:border-red-900 dark:bg-red-950 dark:text-red-300">
          {state.error}
        </p>
      )}

      {state.status === "ready" && (
        <div className="flex flex-col gap-6">
          <section>
            <h2 className="text-sm font-medium text-zinc-500">FEMTO — leave-one-bearing-out (mean MAE, seconds)</h2>
            <table className="mt-2 w-full text-left text-sm">
              <tbody>
                {Object.entries(state.data.femto_lobo_mean_mae_by_model).map(([model, mae]) => (
                  <tr key={model} className="border-t border-zinc-200 dark:border-zinc-800">
                    <td className="py-1 pr-3 font-mono">{model}</td>
                    <td className="py-1">{mae.toFixed(0)}s ({(mae / 3600).toFixed(2)}h)</td>
                  </tr>
                ))}
              </tbody>
            </table>
            <p className="mt-1 text-xs text-zinc-500">
              n = {state.data.femto_lobo_overall_by_model.extra_trees?.n ?? "?"} predictions across 6 held-out bearings.
              A model that does not beat naive on a given bearing is reported, not hidden — see per-bearing detail below.
            </p>
          </section>

          <details className="text-sm">
            <summary className="cursor-pointer text-zinc-500">Per-bearing FEMTO detail</summary>
            <table className="mt-2 w-full text-left text-xs">
              <thead className="text-zinc-500">
                <tr>
                  <th className="py-1 pr-3">Bearing</th>
                  <th className="py-1 pr-3">Model</th>
                  <th className="py-1 pr-3">MAE (s)</th>
                  <th className="py-1 pr-3">n</th>
                </tr>
              </thead>
              <tbody>
                {state.data.femto_lobo.map((row) => (
                  <tr key={`${row.held_out_bearing}-${row.model}`} className="border-t border-zinc-200 dark:border-zinc-800">
                    <td className="py-1 pr-3 font-mono">{row.held_out_bearing}</td>
                    <td className="py-1 pr-3">{row.model}</td>
                    <td className="py-1 pr-3">{row.mae_seconds.toFixed(0)}</td>
                    <td className="py-1 pr-3">{row.n}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </details>

          {state.data.college_mean_mae_by_model && (
            <section className="rounded-lg border border-amber-300 bg-amber-50 p-4 dark:border-amber-900 dark:bg-amber-950">
              <h2 className="text-sm font-medium text-amber-900 dark:text-amber-200">College — walk-forward</h2>
              <p className="mt-1 text-xs font-medium text-amber-900 dark:text-amber-200">{state.data.college_naive_caveat}</p>
              <table className="mt-2 w-full text-left text-sm text-amber-900 dark:text-amber-200">
                <tbody>
                  {Object.entries(state.data.college_mean_mae_by_model).map(([model, mae]) => (
                    <tr key={model}>
                      <td className="py-1 pr-3 font-mono">{model}</td>
                      <td className="py-1">{mae.toFixed(0)}s</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </section>
          )}
        </div>
      )}
    </main>
  );
}
