#!/usr/bin/env python
"""Render docs/cross-dataset-results.md from the generated metrics JSON.

Every number in that document is copied here from reports/metrics/*.json by
code - none is typed by hand (.claude/rules/general.md). Re-run after
run_cross_dataset.py / audit_dataset.py.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import pandas as pd

METRICS = Path("reports/metrics")
OUT = Path("docs/cross-dataset-results.md")
CATEGORIES = ["WITHIN-DOMAIN", "ZERO-SHOT", "CALIBRATED", "MULTI-DATASET"]


def _table(df: pd.DataFrame, digits: int = 3) -> str:
    df = df.copy()
    for c in df.columns:
        if pd.api.types.is_float_dtype(df[c]):
            df[c] = df[c].map(lambda v: "n/a" if pd.isna(v) else f"{v:,.{digits}f}")
    head = "| " + " | ".join(map(str, df.columns)) + " |"
    sep = "|" + "|".join("---" for _ in df.columns) + "|"
    rows = ["| " + " | ".join(map(str, r)) + " |" for r in df.itertuples(index=False)]
    return "\n".join([head, sep, *rows])


def main() -> int:
    report = json.loads((METRICS / "cross_dataset.json").read_text())
    s = pd.DataFrame(report["summary"])
    pb = pd.DataFrame(report["per_bearing"])
    code = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True,
                          text=True).stdout.strip()
    lines = [
        "# Cross-dataset results (generated)",
        "",
        f"Generated by `scripts/report_cross_dataset.py` from `reports/metrics/cross_dataset.json`"
        f" (base commit `{code}`, seed {report['config']['seed']}, 90% intervals, "
        f"runtime {report['runtime_s']:.0f} s). Do not edit by hand - re-run the script.",
        "",
        "Units: MAE/RMSE/median AE in **seconds**; *life-fraction MAE* = mean |f_pred - f_true| "
        "with f = elapsed / total life (0 = perfect, a constant guess f = 0.5 scores ~0.25); "
        "*skill* = 1 - fraction MAE / constant-guess MAE (> 0 = better than the guess); "
        "*post-onset* = recordings after the causal SN-HI stage left HEALTHY; over-estimate = "
        "predicted RUL > actual (unsafe direction). Means are over bearings (each bearing "
        "counts once). Evaluated rows: after each bearing's reference window.",
        "",
    ]
    cols = {"experiment": "experiment", "model": "model", "test_domain": "test",
            "n_bearings": "bearings", "n_rows": "rows", "mae_seconds": "MAE s",
            "rmse_seconds": "RMSE s", "median_abs_error_seconds": "median AE s",
            "naive_mae_seconds": "naive MAE s", "fraction_mae": "life-frac MAE",
            "fraction_skill": "skill", "overestimate_pct": "over %",
            "fraction_mae_post_onset": "post-onset life-frac MAE"}
    cov = {"experiment": "experiment", "model": "model", "test_domain": "test",
           "coverage_conformal": "cov. normalised conformal",
           "width_conformal_seconds": "width s", "coverage_conformal_abs": "cov. absolute conformal",
           "width_conformal_abs_seconds": "width s ", "coverage_tree_5_95": "cov. tree 5-95%",
           "width_tree_5_95_seconds": "width s  "}
    for cat in CATEGORIES:
        sub = s[s["category"] == cat].sort_values(["experiment", "model", "test_domain"])
        if sub.empty:
            continue
        lines += [f"## {cat}", "", _table(sub[list(cols)].rename(columns=cols)), "",
                  "Prediction intervals (nominal coverage 0.90):", "",
                  _table(sub[list(cov)].rename(columns=cov)), ""]

    lines += ["## Applicability vs error", ""]
    for model, v in report["applicability_vs_error"].items():
        if not isinstance(v, dict):
            continue
        lines += [f"**{model}** (n = {v['n']} held-out bearing evaluations): Spearman(shift "
                  f"ratio, life-fraction MAE) = {v['spearman_shift_vs_fraction_mae']:.3f}; "
                  f"Spearman(shift ratio, nMAE) = {v['spearman_shift_vs_nmae']:.3f}.", ""]
        by = pd.DataFrame(v["by_level"]).T.reset_index(names="level")
        lines += [_table(by), "", "Post-hoc split by life time-scale (hypothesis-generating, "
                  "not used to tune the policy):", "",
                  _table(pd.DataFrame(v["by_life_scale_post_hoc"]).T.reset_index(names="group")),
                  ""]

    lines += ["## Health indicator across datasets", ""]
    rows = [{"dataset": d, "HI": h, "bearings": m["n_bearings"],
             "monotonicity": m.get("monotonicity_mean"),
             "trendability (min abs Spearman)": m.get("trendability_min_abs_spearman"),
             "mean Spearman(HI, elapsed)": m.get("spearman_elapsed_mean"),
             "prognosability": m.get("prognosability"),
             "mean Spearman(HI, RUL)": m.get("spearman_rul_mean")}
            for d, v in report["health_indicator"].items() for h, m in v.items()]
    lines += [_table(pd.DataFrame(rows)), ""]

    keep = ["experiment", "model", "bearing_run_id", "n", "mae_seconds", "fraction_mae",
            "fraction_skill", "overestimate_pct", "coverage_conformal_abs"]
    lines += ["## Per-bearing results", "",
              _table(pb.sort_values(["category", "experiment", "model", "bearing_run_id"])[keep]),
              ""]

    audit_path = METRICS / "audit_college.json"
    if audit_path.exists():
        a = json.loads(audit_path.read_text())["bearings"]["college:nsk6205"]
        lines += ["## College data-quality audit (every sample of every file)", "",
                  "```json", json.dumps(a, indent=1), "```", ""]
    OUT.write_text("\n".join(lines))
    print(f"Wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
